import type { ReactElement } from 'react';

export type AuthProviderIcon = 'google' | 'apple' | 'solana' | 'passkey';
export type AuthProviderIconId = AuthProviderIcon | 'webauthn';

export interface ProviderIconProps {
  className?: string;
  size?: number | string;
}

export function authProviderIcon(
  provider: AuthProviderIconId,
  props: ProviderIconProps = {}
): ReactElement {
  switch (normalizeProviderIcon(provider)) {
    case 'google':
      return <GoogleProviderIcon {...props} />;
    case 'apple':
      return <AppleProviderIcon {...props} />;
    case 'passkey':
      return <PasskeyProviderIcon {...props} />;
    case 'solana':
      return <SolanaProviderIcon {...props} />;
  }
}

